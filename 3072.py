vowel = input().lower()

if "a" in vowel:
    print(f"a : {vowel.count("a")}")
if "e" in vowel:
    print(f"e : {vowel.count("e")}")
if "i" in vowel:
    print(f"i : {vowel.count("i")}")
if "o" in vowel:
    print(f"o : {vowel.count("o")}")
if "u" in vowel:
    print(f"u : {vowel.count("u")}")
